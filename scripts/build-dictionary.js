// Builds the game dictionary from the word lists in data/.
//   node scripts/build-dictionary.js
//
// Sources:
// - data/enable1.txt: the ENABLE word list (public domain).
// - data/offensive-words-en.txt: "List of Dirty, Naughty, Obscene, and
//   Otherwise Bad Words" by Shutterstock (LDNOOBW), CC BY 4.0. Used to remove
//   offensive words so they never score or appear in results.
// - data/scowl-english-levels.txt: word commonness levels from SCOWL
//   (Kevin Atkinson; notice in data/SCOWL-COPYRIGHT.txt). House players use
//   them to favour everyday words over obscure ones.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const MIN = 3;
const MAX = 16; // the longest word a 4x4 board can hold

const read = (file) =>
  fs
    .readFileSync(path.join(root, file), 'utf8')
    .split(/\r?\n/)
    .map((w) => w.trim().toLowerCase())
    .filter(Boolean);

// Block each offensive word and its common inflections.
const SUFFIXES = ['', 's', 'es', 'ed', 'ing', 'er', 'ers', 'y', 'ies'];
const blocked = new Set();
for (const w of read('data/offensive-words-en.txt')) {
  if (!/^[a-z]+$/.test(w)) continue; // phrases can't be traced on a board
  for (const s of SUFFIXES) blocked.add(w + s);
}

const words = [...new Set(read('data/enable1.txt'))]
  .filter((w) => /^[a-z]+$/.test(w) && w.length >= MIN && w.length <= MAX && !blocked.has(w))
  .sort();

// Commonness per word: 1 everyday (SCOWL 10–20), 2 familiar (35), 3 uncommon
// (40–50), 4 rare (55+ or not in SCOWL).
const levels = new Map(
  read('data/scowl-english-levels.txt').map((line) => {
    const [w, n] = line.split(' ');
    return [w, Number(n)];
  }),
);
const commonness = (w) => {
  const n = levels.get(w);
  if (n === undefined || n >= 55) return 4;
  if (n <= 20) return 1;
  if (n <= 35) return 2;
  return 3;
};

const out = `// GENERATED by scripts/build-dictionary.js from data/. Do not edit by hand.
// ${words.length} words, ${MIN}–${MAX} letters, sorted, lower case, newline separated.
// Word list: ENABLE (public domain). Offensive words removed using LDNOOBW (CC BY 4.0).
// Commonness from SCOWL, Copyright 2000-2016 by Kevin Atkinson (see data/SCOWL-COPYRIGHT.txt).

export const WORDS = ${JSON.stringify(words.join('\n'))};

/** One digit per word, same order as WORDS: 1 everyday, 2 familiar, 3 uncommon, 4 rare. */
export const COMMONNESS = ${JSON.stringify(words.map(commonness).join(''))};
`;

const target = path.join(root, 'src/game/engine/words.generated.ts');
fs.writeFileSync(target, out);
const removed = read('data/enable1.txt').filter((w) => blocked.has(w)).length;
console.log(`Wrote ${words.length} words (${removed} offensive removed) to ${path.relative(root, target)}`);
