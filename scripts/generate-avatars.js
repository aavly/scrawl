// Copies the avatar art from the design generator into the app as plain data.
// Re-run after the design chat or an illustrator updates the art:
//   node scripts/generate-avatars.js

const fs = require('fs');
const path = require('path');

const art = require('../docs/design/source/generator/avatars.js');

// The design files use p1..p8 for the player avatars; the app uses their names.
const PLAYER_IDS = {
  p1: 'sprout',
  p2: 'haze',
  p3: 'marlow',
  p4: 'juno',
  p5: 'kit',
  p6: 'ash',
  p7: 'wren',
  p8: 'teddy',
};

const squash = (svg) => svg.replace(/\s*\n\s*/g, ' ').trim();

const house = Object.entries(art.CHAR).map(([id, c]) => ({ id, family: 'house', name: c.name, bg: c.bg, svg: squash(c.svg) }));
const players = Object.entries(art.PLAYER).map(([key, p]) => ({
  id: PLAYER_IDS[key],
  family: 'player',
  name: p.name,
  bg: p.bg,
  svg: squash(p.svg),
}));

const entries = [...house, ...players]
  .map((a) => `  ${a.id}: ${JSON.stringify({ family: a.family, name: a.name, bg: a.bg, svg: a.svg })},`)
  .join('\n');

const out = `// GENERATED by scripts/generate-avatars.js from docs/design/source/generator/avatars.js.
// Do not edit by hand. Each svg is the inner markup of a 100x100 viewBox.

export const avatarArt = {
${entries}
} as const;
`;

const target = path.join(__dirname, '../src/components/avatar/art.generated.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`Wrote ${house.length + players.length} avatars to ${path.relative(process.cwd(), target)}`);
